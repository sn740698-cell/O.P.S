"""
O.P.S. 2.0 Desktop Automation Engine — Module 4: Code Generation and File Writer
Integrates local Qwen3 1.7B to synthesize, validate, and safely write or edit code files.
Supports Python, JavaScript, TypeScript, HTML, CSS, JSX, JSON, and SQL.
Provides AST syntax checks for Python, JSON validation, automatic .bak backups,
targeted non-destructive edits preserving comments and imports, and direct typing into active desktop editors.
"""

import os
import re
import ast
import json
import logging
from typing import Dict, Any, List, Optional, Tuple
from research_system.llm.ollama_client import ollama_client, MODEL_QWEN_1_7B
from automation_system.desktop.file_controller import FileController
from automation_system.desktop.gui_controller import GUIController

logger = logging.getLogger("OPS.Desktop.CodeWriter")

# Extension mapping to canonical languages
EXTENSION_MAP = {
    ".py": "python",
    ".js": "javascript",
    ".jsx": "javascript",
    ".ts": "typescript",
    ".tsx": "typescript",
    ".html": "html",
    ".css": "css",
    ".json": "json",
    ".sql": "sql",
    ".md": "markdown",
    ".txt": "text"
}


class CodeWriter:
    """
    Code generation, file creation, targeted editing, and editor actuation engine.
    """

    @classmethod
    def clean_code_block(cls, raw_output: str) -> str:
        """
        Strips markdown code fences (```python ... ```) and conversational boilerplate.
        """
        text = raw_output.strip()
        # Remove opening ```language
        text = re.sub(r"^```[a-zA-Z0-9_\-]*\r?\n", "", text)
        # Remove closing ```
        text = re.sub(r"\r?\n```$", "", text)
        return text.strip()

    @classmethod
    def infer_language_from_path(cls, path: str) -> str:
        """
        Infers programming language from file extension.
        """
        _, ext = os.path.splitext(path.lower())
        return EXTENSION_MAP.get(ext, "python")

    @classmethod
    def validate_syntax(cls, code: str, language: str) -> Tuple[bool, Optional[str]]:
        """
        Performs static syntax verification prior to writing to disk.
        """
        lang = language.lower()
        if lang == "python":
            try:
                ast.parse(code)
                return True, None
            except SyntaxError as se:
                return False, f"Python SyntaxError at line {se.lineno}: {se.msg}"
        elif lang == "json":
            try:
                json.loads(code)
                return True, None
            except json.JSONDecodeError as jde:
                return False, f"JSON DecodeError: {jde.msg}"
        return True, None

    @classmethod
    def generate_code(
        cls,
        prompt: str,
        language: str = "python",
        file_path: Optional[str] = None
    ) -> str:
        """
        Prompts Qwen3 1.7B to produce complete, correct source code according to directive.
        """
        system_prompt = (
            f"You are the O.P.S. 2.0 Autonomous Code Generation Engine. "
            f"Generate clean, robust, complete, and runnable {language.upper()} code for the requested directive. "
            f"Output ONLY the raw source code. "
            f"DO NOT include markdown backticks (```), conversational commentary, explanations, or notes. "
            f"Ensure correct syntax, proper indentation, and necessary imports."
        )

        user_prompt = f"Directive: {prompt}"
        if file_path:
            user_prompt += f"\nTarget file: {os.path.basename(file_path)}"

        try:
            raw_response = ollama_client.generate(
                model=MODEL_QWEN_1_7B,
                prompt=user_prompt,
                system_prompt=system_prompt,
                temperature=0.1,
                num_predict=2048
            )
            cleaned = cls.clean_code_block(raw_response)
            return cleaned
        except Exception as e:
            logger.error(f"Ollama code generation failed: {e}")
            # Fallback template if Ollama is unreachable
            if language.lower() == "python":
                return f"# Generated by O.P.S. 2.0\n# Directive: {prompt}\n\ndef main():\n    print('Executing: {prompt}')\n\nif __name__ == '__main__':\n    main()\n"
            return f"// Generated by O.P.S. 2.0\n// Directive: {prompt}\n"

    @classmethod
    def write_code_file(
        cls,
        path: str,
        code: Optional[str] = None,
        prompt: Optional[str] = None,
        language: Optional[str] = None,
        overwrite: bool = True
    ) -> Dict[str, Any]:
        """
        Generates and writes complete code file to disk.
        """
        target_path = FileController.resolve_safe_path(path)
        lang = language or cls.infer_language_from_path(target_path)

        final_code = code
        if not final_code and prompt:
            final_code = cls.generate_code(prompt=prompt, language=lang, file_path=target_path)

        if not final_code:
            return {"success": False, "action": "write_code_file", "path": target_path, "error": "No code or prompt provided."}

        # Validate syntax
        is_valid, err = cls.validate_syntax(final_code, lang)
        if not is_valid and lang in ["python", "json"]:
            logger.warning(f"Syntax validation warning for {lang}: {err}")

        # Write to disk
        write_res = FileController.create_file(target_path, content=final_code, overwrite=overwrite)
        write_res["language"] = lang
        write_res["syntax_valid"] = is_valid
        write_res["ast_valid"] = is_valid
        if err:
            write_res["syntax_warning"] = err
        return write_res

    @classmethod
    def edit_existing_code_file(
        cls,
        path: str,
        instruction: str,
        backup: bool = True
    ) -> Dict[str, Any]:
        """
        Safely modifies an existing source file using Qwen3 1.7B.
        Preserves existing comments, docstrings, imports, and unmodified functions.
        """
        target_path = FileController.resolve_safe_path(path)
        if not os.path.exists(target_path):
            return {"success": False, "action": "edit_code_file", "path": target_path, "error": f"File '{target_path}' does not exist."}

        # 1. Read existing content
        read_res = FileController.read_file(target_path)
        if not read_res.get("success"):
            return read_res
        original_code = read_res.get("content", "")

        # 2. Create backup (.bak)
        backup_path = f"{target_path}.bak"
        if backup:
            import shutil
            shutil.copy2(target_path, backup_path)

        lang = cls.infer_language_from_path(target_path)

        # 3. Prompt Qwen3 1.7B to perform the exact update preserving everything else
        system_prompt = (
            f"You are the O.P.S. 2.0 Autonomous Code Refactoring Engine. "
            f"Modify the provided {lang.upper()} source code according to the instruction. "
            f"CRITICAL RULES: "
            f"1. Preserve ALL existing imports, comments, docstrings, functions, and classes unless the instruction explicitly specifies removing them. "
            f"2. Maintain the existing coding style, indentation, and structure. "
            f"3. Return the COMPLETE updated source file. "
            f"4. Output ONLY the raw source code without markdown fences (```) or conversational remarks."
        )

        user_prompt = (
            f"Target File: {os.path.basename(target_path)}\n"
            f"Instruction: {instruction}\n\n"
            f"--- ORIGINAL SOURCE CODE ---\n"
            f"{original_code}\n"
            f"--- END ORIGINAL SOURCE CODE ---\n\n"
            f"Provide the complete updated source code:"
        )

        try:
            updated_raw = ollama_client.generate(
                model=MODEL_QWEN_1_7B,
                prompt=user_prompt,
                system_prompt=system_prompt,
                temperature=0.1,
                num_predict=3072
            )
            updated_code = cls.clean_code_block(updated_raw)

            # Validate syntax if python or json
            is_valid, err = cls.validate_syntax(updated_code, lang)
            if not is_valid and lang == "python":
                logger.warning(f"Updated python syntax error ({err}). Reverting to backup.")
                return {
                    "success": False,
                    "action": "edit_code_file",
                    "path": target_path,
                    "error": f"Generated code had syntax error ({err}). Original file was kept intact."
                }

            with open(target_path, "w", encoding="utf-8") as f:
                f.write(updated_code)

            return {
                "success": True,
                "action": "edit_code_file",
                "path": target_path,
                "backup_path": backup_path,
                "old_size": len(original_code),
                "new_size": len(updated_code),
                "language": lang,
                "message": f"Successfully edited '{os.path.basename(target_path)}' per instruction."
            }

        except Exception as e:
            logger.error(f"Failed to edit code file via LLM: {e}")
            return {"success": False, "action": "edit_code_file", "path": target_path, "error": str(e)}

    @classmethod
    def type_into_active_editor(
        cls,
        window_title: str,
        code: Optional[str] = None,
        prompt: Optional[str] = None,
        language: str = "text"
    ) -> Dict[str, Any]:
        """
        Types code directly into an active editor window (e.g. Notepad, VS Code) using GUIController.
        """
        final_code = code
        if not final_code and prompt:
            final_code = cls.generate_code(prompt=prompt, language=language)

        if not final_code:
            return {"success": False, "action": "type_into_editor", "error": "No code or prompt to type."}

        gui = GUIController()
        return gui.type_text(title=window_title, text=final_code, replace=False)
